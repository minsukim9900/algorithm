SELECT
    I.ID,
    N.FISH_NAME,
    I.LENGTH
FROM FISH_INFO I
JOIN FISH_NAME_INFO N
  ON N.FISH_TYPE = I.FISH_TYPE
WHERE I.LENGTH = (SELECT
                     MAX(F.LENGTH)
                 FROM FISH_INFO F
                 WHERE I.FISH_TYPE = F.FISH_TYPE
                 GROUP BY F.FISH_TYPE)
ORDER BY ID ASC;