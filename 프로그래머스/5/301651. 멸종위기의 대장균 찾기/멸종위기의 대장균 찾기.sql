WITH RECURSIVE GENERATIONS AS (
    SELECT
        ID,
        1 AS GENERATION
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    SELECT
        C.ID,
        G.GENERATION + 1
    FROM ECOLI_DATA C
    JOIN GENERATIONS G
        ON C.PARENT_ID = G.ID
)
SELECT
    COUNT(*) AS `COUNT`,
    G.GENERATION
FROM GENERATIONS G
WHERE NOT EXISTS (
    SELECT 1
    FROM ECOLI_DATA C
    WHERE C.PARENT_ID = G.ID
)
GROUP BY G.GENERATION
ORDER BY G.GENERATION;